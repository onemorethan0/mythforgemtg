def percentile_band(bracket: int, metric: str, value: float | None,
                    table: dict[int, dict[str, dict]] | None = None) -> dict | None:
    """Where `value` falls in the reference distribution for `bracket`/`metric`.

    Returns None when the value is missing, the cell is unknown, thin (n < 20) or has no
    percentiles -- an honest decline, never a guess. Otherwise
    {"bracket", "p25", "p50", "p75", "n", "percentile_band"} with the band one of
    "below_p25" (< p25), "p25_p50" (p25 <= v < p50), "p50_p75" (p50 <= v < p75),
    "above_p75" (>= p75). The band describes the RAW value; for `LOWER_IS_BETTER` metrics
    "below_p25" is the FAST end.
    """
    if value is None:
        return None
    ref = BRACKET_AXIS_REFERENCE if table is None else table
    cell = ref.get(bracket, {}).get(metric)
    if not cell or cell.get("thin"):
        return None
    p25, p50, p75 = cell.get("p25"), cell.get("p50"), cell.get("p75")
    if p25 is None or p50 is None or p75 is None:
        return None
    if value < p25:
        band = "below_p25"
    elif value < p50:
        band = "p25_p50"
    elif value < p75:
        band = "p50_p75"
    else:
        band = "above_p75"
    return {"bracket": bracket, "p25": p25, "p50": p50, "p75": p75,
            "n": cell["n"], "percentile_band": band}


GRID_STEP = 5.0   # `q` holds p0, p5, ..., p100


def rank_in_grid(grid: list[float], value: float) -> float:
    """Percentile rank (0-100) of `value` in a p0..p100 grid at `GRID_STEP` spacing, by linear
    interpolation. A value on a plateau (many decks share one score) gets the plateau's MIDDLE,
    so a tie is never credited as beating the whole tie."""
    if value < grid[0]:
        return 0.0
    if value > grid[-1]:
        return 100.0
    equal = [i for i, g in enumerate(grid) if g == value]
    if equal:
        return GRID_STEP * (equal[0] + equal[-1]) / 2
    i = max(k for k, g in enumerate(grid) if g < value)
    lo, hi = grid[i], grid[i + 1]
    return GRID_STEP * (i + (value - lo) / (hi - lo))


def percentile_rank(bracket: int, metric: str, value: float | None,
                    table: dict[int, dict[str, dict]] | None = None) -> dict | None:
    """Where `value` ranks among the labelled corpus decks of `bracket` (B37).

    Returns {"bracket", "rank", "better_than", "n"} -- `rank` is the RAW percentile (share of
    peers with a lower value); `better_than` is oriented, so for a `LOWER_IS_BETTER` metric it
    is 100 - rank. None when the value is missing or the cell is thin or has no grid (a
    reference baked before B37): an honest decline, never a guess."""
    if value is None:
        return None
    ref = BRACKET_AXIS_REFERENCE if table is None else table
    cell = ref.get(bracket, {}).get(metric)
    if not cell or cell.get("thin") or not cell.get("q"):
        return None
    rank = rank_in_grid(cell["q"], float(value))
    better = 100.0 - rank if metric in LOWER_IS_BETTER else rank
    return {"bracket": bracket, "rank": round(rank, 1), "better_than": round(better, 1),
            "n": cell["n"]}
