"""Strength placement: where a deck's measured speed + strength put it among player brackets.

The official Commander Brackets are written as a ladder of expectations (how fast, how
consistent, how much it disrupts), and the Game Changer list is an ALLOWANCE on that ladder:
a deck needs Bracket 3 to play 1-3 Game Changers and Bracket 4 to play more. The rules never
say a zero-Game-Changer deck IS Bracket 2. The previous estimator read them that way -- every
zero-GC deck was capped at [1, 2] -- so a fast, tuned deck with no listed cards could never
read Upgraded. `estimate_bracket` now uses the gates only as FLOORS and asks this module where
the deck's strength places it.

THE MODEL. One linear "strength score" on the bracket scale, over the measured axes and the
card-quality signals players actually build strength from (fast mana, tutors, cheap answers,
curve, mana base), with the Game Changer count as one input among them. Fitted by ridge
regression on player-labelled corpus decks (the label is the builder's own Archidekt bracket:
self-reported consensus, not ground truth), then cut into brackets at points chosen to
maximise agreement with those players. `scripts/bracket_strength_fit.py --bake` regenerates the
block below; `--check` detects drift. It is fitted on the FULL compiled semantics store, which
is what the live engine runs.

WHAT THE FIT FOUND, recorded because it shapes how far this can go (619 labelled decks,
2026-10-18): the goldfish axes barely separate the brackets players assign (every |rho| <=
0.15; nearly every B1-B4 deck goldfishes around turn 9-10), and the Game Changer count is
still the strongest single signal (~6x the next). The fit is SIGN-CONSTRAINED (`SIGNS`): a
signal may only push the bracket the way Magic says it does, so the pure goldfish-speed
signals -- kill rate, kill turn, kill speed (clock), commander turn, wipe resilience -- come
out at weight 0: once card quality is in, they add nothing that matches player labels, and
left free the regression gave them small WRONG-way weights. Speed still enters through
multiplayer closing power (pod), ceiling and consistency. A speed-ONLY rule matched players
worse than the old gates (40% exact vs 51%); this hybrid cross-validated at 57.5% exact vs
52.8% for the gate-banded estimator on the same 619 decks, every casual bracket's recall at
or above the old one (B1 39/37, B2 56/50, B3 75/74), B5 recall 84% vs 35%, and the honest
loss B4 34% vs 51% (see `MODEL_NOTE`). Not a verdict on the pilot; the reasons list says
which signals moved the placement.

Community salt (`table_feel`) is deliberately NOT an input: the bracket stays about power.
"""

