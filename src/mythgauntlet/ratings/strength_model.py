BORDERLINE = 0.2  # a score this close below the next cut reads "plays up"


@dataclass
class StrengthReading:
    score: float            # on the bracket scale (1..5-ish)
    bracket: int            # 1-5 from the cut points
    plays_up: bool          # within BORDERLINE of the next bracket's cut
    margin: float           # distance to the nearest cut (confidence input)
    drivers: list[tuple[str, float]] = field(default_factory=list)  # (feature, contribution)


def card_quality(cards: list[tuple[Card, int]], commanders: list[Card]) -> dict[str, float]:
    """The card-level strength signals, shared by the live estimator and the fit script."""
    entries = list(cards) + [(c, 1) for c in commanders]
    nonland = [(c, q) for c, q in entries if not c.is_land]
    fast = tut = cheap = 0.0
    mvs: list[float] = []
    for card, q in nonland:
        fx = tags.analyze(card)
        if (fx.ramp_sources or fx.ritual_mana) and card.mana_value <= 2:
            fast += q
        if fx.tutor:
            tut += q
        if (fx.removal or fx.counterspell) and card.mana_value <= 2:
            cheap += q
        mvs.extend([float(card.mana_value)] * q)
    return {
        "gc": float(len({c.name for c, _ in entries if c.game_changer})),
        "fast_mana": fast, "tutors": tut, "cheap_interaction": cheap,
        "avg_mv": sum(mvs) / len(mvs) if mvs else 0.0,
    }


def features(
    *, cards: list[tuple[Card, int]], commanders: list[Card], horizon: int,
    consistency: float, kill_rate: float, avg_kill_turn: float | None,
    avg_commander_turn: float | None, resilience: float | None, interaction: float,
    ceiling: float, pod: float, manabase: float,
) -> dict[str, float | None]:
    """Every model input from what `analyze_deck` already measured. `resilience` may be None
    (not run): `strength_placement` then scores it at the corpus mean, i.e. neutral."""
    clock = (0.0 if avg_kill_turn is None
             else max(0.0, min(100.0, 100.0 * (horizon - avg_kill_turn) / horizon)))
    return {
        **card_quality(cards, commanders),
        "consistency": consistency, "speed": kill_rate * 100.0,
        "resilience": resilience, "interaction": interaction, "ceiling": ceiling,
        "clock": clock, "pod": pod, "manabase": manabase,
        # a deck that never kills / never casts its commander sits at the horizon
        "avg_kill_turn": float(horizon) if avg_kill_turn is None else avg_kill_turn,
        "avg_commander_turn": float(horizon) if avg_commander_turn is None else avg_commander_turn,
    }


def is_fitted() -> bool:
    return bool(WEIGHTS) and all(f in WEIGHTS for f in FEATURES)


def strength_placement(feats: dict[str, float | None]) -> StrengthReading | None:
    """None when the model is not fitted (the estimator then falls back to its gates)."""
    if not is_fitted():
        return None
    contrib: dict[str, float] = {}
    for f in FEATURES:
        v = feats.get(f)
        z = 0.0 if v is None else (float(v) - MEANS[f]) / (SCALES[f] or 1.0)
        contrib[f] = WEIGHTS[f] * z
    score = INTERCEPT + sum(contrib.values())
    bracket = 1 + bisect_right(CUTS, score)
    nxt = CUTS[bracket - 1] if bracket <= len(CUTS) else None
    margin = min(abs(score - c) for c in CUTS)
    drivers = sorted(((f, c) for f, c in contrib.items() if f != "gc"), key=lambda t: -abs(t[1]))
    return StrengthReading(
        score=round(score, 3), bracket=bracket,
        plays_up=nxt is not None and nxt - score <= BORDERLINE,
        margin=round(margin, 3), drivers=drivers[:3],
    )
