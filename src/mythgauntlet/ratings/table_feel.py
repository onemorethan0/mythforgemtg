"""Table feel: how SALTY a deck will read to a casual pod (EDHREC community salt).

Every other axis asks how strong a deck is. A casual pod asks a second question first --
*will this be fun to sit across from?* -- and no amount of simulation answers it: Armageddon,
Stasis and Rhystic Study are not the strongest cards in Magic, they are the ones players most
resent. EDHREC measures exactly that with a yearly community survey (each card rated 0-4);
`data/salt.py` stores it. This axis turns it into a deck figure.

  * `total_salt`  -- the summed salt of every card the pilot CHOSE (commander and nonbasic
    lands included, basic lands excluded), scaled up when a few are unmeasured. One Armageddon
    (2.98) weighs as much as twelve Llanowar Elves (0.25), which is how a table experiences it.
    BASICS ARE EXCLUDED because their survey scores are noise -- Island 0.90, Forest 0.62,
    Plains 0.27 -- and nobody chooses a basic: with them in, 30 Islands were 27 of a mono-blue
    control deck's 58 salt and every mono-blue deck read salty. Nonbasics are real choices and
    stay (Gaea's Cradle 2.23, The Tabernacle at Pendrell Vale 2.83).
  * `score`       -- where that total sits among the corpus decks, as a 0-100 percentile
    (higher = saltier). RELATIVE, like the off-meta read: "salty" means saltier than most real
    decks, not an absolute verdict on the pilot.
  * `salty_cards` -- the deck's saltiest cards at or above `NOTICEABLE_CARD` (1.0), saltiest
    first: what to raise in the pre-game talk. A deck can read salty from MANY mid-salt cards
    (eight counterspells, five wipes) with none past 1.5, so listing only the >= 1.5 ones
    named Sol Ring alone for a deck whose salt was its counter suite. `salty_count` still
    counts the >= `SALTY_CARD` (1.5) cards, the ones the survey leans "annoying" on.

Measured over the 1,105-deck corpus (2026-10-18): the mean deck total climbs with the labelled
bracket -- B1 22 / B2 26 / B3 34 / B4 45 / B5 71 -- a different lens from power, NOT a bracket
gate: `estimate_bracket` does not read it. Bands are percentile cuts (`FRIENDLY_MAX`,
`SALTY_MIN`); by label they come out B1 74% / B2 58% friendly, B3 66% spicy, B4 52% / B5 93%
salty -- and 3-4% of B1-B2 decks read salty, the "on-level but unfun" deck a casual pod wants
flagged.

The store is optional. With no store, or too few cards measured, the report is
`available=False` and says so; an unmeasured deck is never reported as a friendly one.
"""

from __future__ import annotations

from bisect import bisect_right
from dataclasses import dataclass, field

from mythgauntlet.data.salt import SaltDb, load_salt
from mythgauntlet.model.card import Card

SALTY_CARD = 1.5        # a card at/above this reads "annoying" on the survey's 0-4 scale
NOTICEABLE_CARD = 1.0   # listed among the deck's saltiest cards from here up
MIN_COVERAGE = 0.6      # below this share of cards measured, no deck figure is claimed
FRIENDLY_MAX = 40.0     # score (percentile) below this: friendlier than most decks
SALTY_MIN = 80.0        # score at/above this: saltier than four in five decks
_MAX_LISTED = 8

# === BEGIN GENERATED: SALT_PERCENTILES ===
# Generated by scripts/salt_reference.py: deck total salt at p0, p5, ..., p100 over the corpus.
# Do not edit by hand; re-run `python scripts/salt_reference.py --bake` (`--check` detects drift).
SALT_PERCENTILES: tuple[float, ...] = (0.53, 14.9, 17.31, 19.18, 20.85, 22.0, 23.44, 24.97, 26.35, 27.63, 29.06, 30.27, 31.81, 33.89, 35.82, 38.08, 41.6, 46.39, 53.3, 65.47, 101.74)
SALT_REFERENCE_DECKS = 1105
# === END GENERATED: SALT_PERCENTILES ===


@dataclass
class TableFeelReport:
    available: bool
    score: float | None = None        # 0-100 percentile among corpus decks (higher = saltier)
    band: str = "unavailable"         # friendly | spicy | salty | unavailable
    total_salt: float | None = None   # summed salt, scaled to the full deck
    mean_salt: float | None = None
    salty_count: int = 0              # copies at/above SALTY_CARD
    salty_cards: list[tuple[str, float]] = field(default_factory=list)  # saltiest first
    commander_salt: float | None = None   # the saltiest commander's own score
    measured: int = 0
    total: int = 0
    source_date: str | None = None
    reason: str = ""                  # why unavailable, when it is


def _chosen(card: Card) -> bool:
    """Basic lands are not a choice and their survey scores are noise (module docstring)."""
    return not (card.is_land and card.has_type("basic"))


def deck_salt_figures(entries: list[tuple[Card, int]], db: SaltDb) -> tuple[float, int, int]:
    """(scaled total salt, measured copies, total copies) over the CHOSEN cards -- the one
    definition the axis and the calibration script share, so the baked percentiles measure
    what the axis reports."""
    total = measured = 0
    raw = 0.0
    for card, count in entries:
        if not _chosen(card):
            continue
        total += count
        value = db.get(card)
        if value is None:
            continue
        measured += count
        raw += value * count
    scaled = raw * total / measured if measured else 0.0
    return scaled, measured, total


def percentile_of(total_salt: float, table: tuple[float, ...] = SALT_PERCENTILES) -> float | None:
    """Linear interpolation of `total_salt` into a p0..p100 (step 100/(len-1)) table."""
    if len(table) < 2:
        return None
    step = 100.0 / (len(table) - 1)
    if total_salt <= table[0]:
        return 0.0
    if total_salt >= table[-1]:
        return 100.0
    i = bisect_right(table, total_salt) - 1
    lo, hi = table[i], table[i + 1]
    frac = (total_salt - lo) / (hi - lo) if hi > lo else 0.0
    return round((i + frac) * step, 1)


def band_for(score: float | None) -> str:
    if score is None:
        return "unavailable"
    if score < FRIENDLY_MAX:
        return "friendly"
    if score >= SALTY_MIN:
        return "salty"
    return "spicy"


def compute_table_feel(
    cards: list[tuple[Card, int]], commanders: list[Card], db: SaltDb | None = None,
) -> TableFeelReport:
    db = db if db is not None else load_salt()
    if db is None:
        return TableFeelReport(
            available=False,
            reason="no salt store -- run 'mythgauntlet fetch-salt' (or fetch-data)",
        )
    entries = list(cards) + [(c, 1) for c in commanders]
    total_salt, measured, total = deck_salt_figures(entries, db)
    if not total or measured / total < MIN_COVERAGE:
        return TableFeelReport(
            available=False, measured=measured, total=total, source_date=db.mtgjson_date,
            reason=f"only {measured} of {total} cards have a community salt score",
        )
    score = percentile_of(total_salt)
    salty: dict[str, float] = {}
    salty_count = 0
    for card, count in entries:
        value = db.get(card)
        if value is None or not _chosen(card):
            continue
        if value >= NOTICEABLE_CARD:
            salty[card.name] = value
        if value >= SALTY_CARD:
            salty_count += count
    ranked = sorted(salty.items(), key=lambda kv: (-kv[1], kv[0]))
    commander_scores = [v for c in commanders if (v := db.get(c)) is not None]
    return TableFeelReport(
        available=score is not None,
        score=score,
        band=band_for(score),
        total_salt=round(total_salt, 1),
        mean_salt=round(total_salt / total, 2),
        salty_count=salty_count,
        salty_cards=ranked[:_MAX_LISTED],
        commander_salt=max(commander_scores) if commander_scores else None,
        measured=measured,
        total=total,
        source_date=db.mtgjson_date,
        reason="" if score is not None else "no baked salt reference (run salt_reference.py)",
    )
