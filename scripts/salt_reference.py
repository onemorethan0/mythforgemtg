"""Bake the corpus distribution of deck salt into ratings/table_feel.SALT_PERCENTILES.

The Table feel score is a percentile, so it needs the population it is a percentile OF: every
resolvable corpus deck's `deck_salt_figures` total (the same function the axis calls), at
p0, p5, ..., p100. Decks under the axis's own MIN_COVERAGE are left out, as the axis would
refuse to score them.

    python scripts/salt_reference.py           # print the table
    python scripts/salt_reference.py --bake    # rewrite the generated block
    python scripts/salt_reference.py --check   # exit 1 if the baked table has drifted

Needs the salt store (`mythgauntlet fetch-salt`). Re-run after a salt refresh or a big corpus
change; `--check` tolerates 0.5 salt of drift per cut (survey noise, not a real shift).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from mythgauntlet import cli  # noqa: E402
from mythgauntlet.data.salt import load_salt  # noqa: E402
from mythgauntlet.model.deck import Deck, resolve  # noqa: E402
from mythgauntlet.ratings import table_feel  # noqa: E402

TARGET = REPO / "src" / "mythgauntlet" / "ratings" / "table_feel.py"
_BLOCK = re.compile(
    r"(# === BEGIN GENERATED: SALT_PERCENTILES ===\n)(.*?)(# === END GENERATED: SALT_PERCENTILES ===)",
    re.S,
)
TOLERANCE = 0.5


def measure() -> list[float]:
    db = load_salt()
    if db is None:
        sys.exit("No salt store - run `mythgauntlet fetch-salt` first.")
    cards = cli._load_db()
    totals = []
    for path in sorted((REPO / "corpus" / "decks").glob("*.txt")):
        resolved = resolve(Deck.parse_text(path.read_text(encoding="utf-8"), name=path.stem), cards)
        if not resolved.cards or not resolved.commanders:
            continue
        entries = list(resolved.cards) + [(c, 1) for c in resolved.commanders]
        total, measured, n = table_feel.deck_salt_figures(entries, db)
        if n and measured / n >= table_feel.MIN_COVERAGE:
            totals.append(total)
    return sorted(totals)


def cuts(totals: list[float]) -> tuple[float, ...]:
    n = len(totals)
    out = []
    for k in range(21):
        pos = (n - 1) * k / 20
        lo = int(pos)
        hi = min(n - 1, lo + 1)
        out.append(round(totals[lo] + (totals[hi] - totals[lo]) * (pos - lo), 2))
    return tuple(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--bake", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    totals = measure()
    table = cuts(totals)
    print(f"{len(totals)} decks; p0..p100: {table}")
    if args.check:
        baked = table_feel.SALT_PERCENTILES
        if len(baked) != len(table) or any(abs(a - b) > TOLERANCE for a, b in zip(baked, table)):
            print(f"DRIFT: baked {baked}")
            return 1
        print("baked table is current")
        return 0
    if args.bake:
        body = (
            "# Generated by scripts/salt_reference.py: deck total salt at p0, p5, ..., p100 over the corpus.\n"
            "# Do not edit by hand; re-run `python scripts/salt_reference.py --bake` (`--check` detects drift).\n"
            f"SALT_PERCENTILES: tuple[float, ...] = {table!r}\n"
            f"SALT_REFERENCE_DECKS = {len(totals)}\n"
        )
        src = TARGET.read_text(encoding="utf-8")
        new, n = _BLOCK.subn(lambda m: m.group(1) + body + m.group(3), src)
        if n != 1:
            sys.exit("generated block not found")
        TARGET.write_text(new, encoding="utf-8")
        print(f"baked into {TARGET.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
